/** 가장 잘 맞는 겹침(%)을 말로 */
export function symWord(a) {
  if (a >= 90) return '접어 포개면 거의 한 장처럼 맞물립니다';
  if (a >= 80) return '접어 포개면 비는 가장자리가 얼마 안 됩니다';
  if (a >= 74) return '접어 포개도 가장자리가 조금씩 남습니다';
  if (a >= 66) return '접어 포개면 남는 가장자리가 눈에 들어옵니다';
  if (a >= 54) return '접어 포개면 한쪽 자락이 길게 삐져나옵니다';
  return '접어 포개면 절반 가까이가 어긋납니다';
}
/** 가장 안 맞는 접기의 겹침(%)을 말로 */
export function weakWord(b) {
  if (b >= 80) return '가장 안 맞는 접기도 여든을 넘깁니다';
  if (b >= 65) return '가장 안 맞는 접기도 3분의 2 가까이는 겹칩니다';
  if (b >= 50) return '가장 안 맞는 접기에서는 절반 안팎만 남습니다';
  if (b >= 35) return '가장 안 맞는 접기에서는 절반에 한참 못 미칩니다';
  return '가장 안 맞는 접기에서는 거의 겹치지 않습니다';
}
/** 두 겹침 값을 견준 말 */
export function cmpWord(x, y) {
  const d = x - y;
  if (Math.abs(d) < 1.5) return '거의 같은 정도';
  return d > 0 ? '더 가지런한 쪽' : '더 비뚤어진 쪽';
}
/** 길쭉함을 말로 */
export function longWord(r) {
  if (r < 1.25) return '긴 쪽과 짧은 쪽이 거의 같은 둥근 편';
  if (r < 1.7) return '긴 쪽이 짧은 쪽보다 눈에 띄게 긴 편';
  if (r < 2.6) return '한 방향으로 길게 뻗은 편';
  return '가늘고 길게 뻗은 편';
}

